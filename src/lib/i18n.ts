export function getLocalizedField<T>(obj: T | null | undefined, fieldName: string, locale: Locale): string {
  if (!obj) return '';
  const localizedKey = `${fieldName}_${locale}` as keyof T;
  const fallbackKey = `${fieldName}_en` as keyof T;
  const directValue = obj[localizedKey] as unknown as string;
  const fallbackValue = obj[fallbackKey] as unknown as string;
  return directValue || fallbackValue || '';
}
